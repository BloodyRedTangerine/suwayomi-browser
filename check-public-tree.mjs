// ---------------------------------------------------------------------------
// Plumbing
// ---------------------------------------------------------------------------
const findings = [];
const allowHits = new Map();
function addFinding(rule, path, detail, line) {
  findings.push({ rule, path, line: line || 0, detail });
}
function posix(path) { return path.split(sep).join('/'); }

function isBinary(buffer) {
  const length = Math.min(buffer.length, 8192);
  for (let index = 0; index < length; index++) if (buffer[index] === 0) return true;
  return false;
}
function snippet(text, index, length) {
  const start = Math.max(0, index - 20);
  return text.slice(start, Math.min(text.length, index + length + 40)).replace(/\s+/g, ' ').trim().slice(0, 100);
}
function lineOf(text, index) {
  let line = 1;
  for (let at = text.indexOf('\n'); at !== -1 && at < index; at = text.indexOf('\n', at + 1)) line++;
  return line;
}

function termAllowed(path, term) {
  for (const [pattern, terms, reason] of TERM_ALLOWLIST) {
    if (!pattern.test(path)) continue;
    if (terms === '*' || terms.includes(term)) {
      const key = pattern.source + '\u0001' + reason;
      allowHits.set(key, (allowHits.get(key) || 0) + 1);
      return true;
    }
  }
  return false;
}

function structuralWaived(path, rule) {
  return STRUCTURAL_ALLOWLIST.some(([pattern, rules]) => pattern.test(path) && rules.includes(rule));
}

/** Content scan used for text files and for decompressed archive members. */
function scanText(path, text, { binary = false } = {}) {
  if (PRIVATE_KEY_MARKER.test(text)) addFinding('private-key', path, 'private key marker');
  for (const [rule, pattern] of PERSONAL) {
    const match = pattern.exec(text);
    if (match) addFinding(rule, path, snippet(text, match.index, match[0].length), lineOf(text, match.index));
  }
  if (!NOTICE_LOCATION.test(path)) {
    const match = GENERIC_EMAIL.exec(text);
    if (match) addFinding('personal-email', path, snippet(text, match.index, match[0].length), lineOf(text, match.index));
  }
  for (const pattern of NSFW_SOURCE_NAMES) {
    const match = pattern.exec(text);
    if (match) addFinding('nsfw-source-name', path, snippet(text, match.index, match[0].length), lineOf(text, match.index));
  }
  if (!binary && PROSE_FILE.test(path) && !path.includes('test/')) {
    URL_PATTERN.lastIndex = 0;
    for (let match; (match = URL_PATTERN.exec(text));) {
      let host = '';
      try { host = new URL(match[0].replace(/[.,;:]+$/, '')).hostname; } catch { continue; }
      if (NEUTRAL_HOSTS.test(host)) continue;
      if (LIVE_PATH.test(match[0]) || QUERY_STRING.test(match[0])) {
        addFinding('live-url', path, match[0].slice(0, 100), lineOf(text, match.index));
      }
    }
  }
  for (const [rule, pattern] of PUBLIC_PATH_LEAKS) {
    const flags = pattern.flags.includes('g') ? pattern.flags : pattern.flags + 'g';
    const global = new RegExp(pattern.source, flags);
    for (let match; (match = global.exec(text));) {
      if (rule === 'home-path' && text.startsWith(EMSCRIPTEN_HOME, match.index)) continue;
      if (rule === 'home-path' && HOME_PATH_ALLOWLIST.some(([pattern]) => pattern.test(path))) { allowHits.set(path + '\u0001home-path exemption (placeholder value in a patch)', 1); continue; }
      addFinding(rule, path, snippet(text, match.index, match[0].length), lineOf(text, match.index));
      break;
    }
  }
  if (!binary) {
    const lower = text.toLowerCase();
    for (const term of CONTENT_TERMS) {
      const index = lower.indexOf(term);
      if (index === -1 || termAllowed(path, term)) continue;
      addFinding('content-term', path, term + ': ' + snippet(text, index, term.length), lineOf(text, index));
    }
    for (const [name, pattern] of CONTENT_REGEXPS) {
      const match = pattern.exec(text);
      if (match && !termAllowed(path, name)) addFinding('content-term', path, name + ': ' + snippet(text, match.index, match[0].length), lineOf(text, match.index));
    }
  } else {
    // Compiled archives: only the Tachiyomi API identifiers are expected; report anything else.
    const lower = text.toLowerCase();
    for (const term of CONTENT_TERMS) {
      const index = lower.indexOf(term);
      if (index === -1 || termAllowed(path, term)) continue;
      addFinding('content-term', path, term + ' (binary): ' + snippet(text, index, term.length));
    }
  }
}

/** Minimal ZIP reader (stored + deflate) so archives inside packages can be scanned without dependencies. */
function* zipMembers(buffer) {
  let eocd = -1;
  for (let at = buffer.length - 22; at >= Math.max(0, buffer.length - 22 - 0xffff); at--) {
    if (buffer.readUInt32LE(at) === 0x06054b50) { eocd = at; break; }
  }
  if (eocd < 0) return;
  const count = buffer.readUInt16LE(eocd + 10);
  let cursor = buffer.readUInt32LE(eocd + 16);
  for (let index = 0; index < count; index++) {
    if (buffer.readUInt32LE(cursor) !== 0x02014b50) return;
    const method = buffer.readUInt16LE(cursor + 10);
    const compressed = buffer.readUInt32LE(cursor + 20);
    const nameLength = buffer.readUInt16LE(cursor + 28);
    const extraLength = buffer.readUInt16LE(cursor + 30);
    const commentLength = buffer.readUInt16LE(cursor + 32);
    const local = buffer.readUInt32LE(cursor + 42);
    const name = buffer.toString('utf8', cursor + 46, cursor + 46 + nameLength);
    cursor += 46 + nameLength + extraLength + commentLength;
    if (name.endsWith('/')) continue;
    const dataStart = local + 30 + buffer.readUInt16LE(local + 26) + buffer.readUInt16LE(local + 28);
    const raw = buffer.subarray(dataStart, dataStart + compressed);
    try { yield [name, method === 0 ? raw : inflateRawSync(raw)]; } catch { yield [name, raw]; }
  }
}

async function scanFile(root, absolute, relativePath, context) {
  const info = await stat(absolute);
  const extension = extname(relativePath).toLowerCase();
  const name = basename(relativePath);
  const treeMode = !context.package;
  if (treeMode) {
    if (!structuralWaived(relativePath, 'size') && info.size > MAX_FILE_BYTES) addFinding('size', relativePath, `${info.size} bytes exceeds ${MAX_FILE_BYTES}`);
    if (extension === '.log' || (extension === '.txt' && !TEXT_DOC_NAME.test(name) && !TEXT_DOC_DIRS.test('/' + relativePath))) addFinding('log-file', relativePath, 'raw run log / text capture');
    if (['.har', '.pcap'].includes(extension)) addFinding('log-file', relativePath, 'raw capture');
    if (RASTER_EXTENSIONS.has(extension) && !structuralWaived(relativePath, 'raster')) addFinding('raster', relativePath, 'screenshot or image');
    if (BINARY_EXTENSIONS.has(extension) && !structuralWaived(relativePath, 'binary')) {
      addFinding(['.pem', '.key', '.p8', '.p12', '.pfx', '.jks', '.keystore', '.der'].includes(extension) ? 'private-key' : 'binary', relativePath, 'binary / key-store file type ' + extension);
    }
  } else {
    if (['.pem', '.key', '.p8', '.p12', '.pfx', '.jks', '.keystore'].includes(extension)) addFinding('private-key', relativePath, 'key file in package');
    if (extension === '.log') addFinding('log-file', relativePath, 'log file in package');
    if (extension === '.map') addFinding('source-map', relativePath, 'source map in package');
  }
  if (info.size > 256 * 1024 * 1024) return;
  const buffer = await readFile(absolute);
  if (PRIVATE_KEY_MARKER.test(buffer.toString('latin1')) && !/check-(?:private|public)-tree\.mjs$/.test(relativePath)) addFinding('private-key', relativePath, 'private key marker in file contents');
  const archive = ['.jar', '.zip', '.xpi', '.apk'].includes(extension);
  if (archive && context.package) {
    for (const [member, bytes] of zipMembers(buffer)) {
      const memberPath = relativePath + '!/' + member;
      scanText(memberPath, bytes.toString('latin1'), { binary: true });
    }
    return;
  }
  const binary = isBinary(buffer);
  if (binary && context.package) {
    if (info.size <= 200 * 1024 * 1024) scanText(relativePath, buffer.toString('latin1'), { binary: true });
    return;
  }
  if (binary) {
    if (!BINARY_EXTENSIONS.has(extension) && !RASTER_EXTENSIONS.has(extension)) addFinding('binary', relativePath, 'unrecognised binary content');
    return;
  }
  if (info.size > 40 * 1024 * 1024) return;
  scanText(relativePath, buffer.toString('utf8'));
}

async function walk(root, context) {
  const visit = async (directory) => {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const absolute = join(directory, entry.name);
      const relativePath = posix(relative(root, absolute));
      if (entry.name === '.git' && !context.package) continue; // repository metadata is not content
      if (entry.isSymbolicLink()) { addFinding('symlink', relativePath, 'symbolic link'); continue; }
      if (entry.isDirectory()) {
        if (!context.package) {
          if (FORBIDDEN_SEGMENTS.has(entry.name) || (relativePath.indexOf('/') === -1 && FORBIDDEN_ROOT_PREFIXES.some(prefix => entry.name.startsWith(prefix) && entry.name !== 'ui-')) ) {
            addFinding('forbidden-directory', relativePath + '/', 'build output, cache, profile or key directory');
            continue;
          }
          if (FORBIDDEN_ROOT_DIRS.some(dir => relativePath === dir || (relativePath === 'browser/' + dir))) {
            addFinding('forbidden-directory', relativePath + '/', 'generated / third-party directory is not tracked');
            continue;
          }
        } else if (['node_modules', '.cache', 'SOURCE', 'test', 'PRIVATE-extension-key'].includes(entry.name) && relativePath.split('/').length <= 2) {
          addFinding('package-content', relativePath + '/', 'must not be shipped in an extension package');
          continue;
        }
        await visit(absolute);
      } else if (entry.isFile()) {
        if (context.package && /^(?:DEVELOPER-SNAPSHOT\.md)$/.test(entry.name)) addFinding('package-content', relativePath, 'developer snapshot must not ship');
        await scanFile(root, absolute, relativePath, context);
      }
    }
  };
  await visit(root);
}

export async function scanTree(root, { package: isPackage = false } = {}) {
  findings.length = 0;
  await walk(resolve(root), { package: isPackage });
  return findings.slice();
}

function printAllowlist() {
  console.log('Structural allowlist (waived rule: reason):');
  for (const [pattern, rules, reason] of STRUCTURAL_ALLOWLIST) console.log(`  ${pattern.source}  [${rules.join(',')}]  ${reason}`);
  console.log('\nContent-term allowlist (path pattern: terms: reason):');
  for (const [pattern, terms, reason] of TERM_ALLOWLIST) console.log(`  ${pattern.source}  [${terms === '*' ? 'all terms' : terms.join(',')}]  ${reason}`);
  for (const [pattern, reason] of HOME_PATH_ALLOWLIST) console.log(`\nPath-leak exemption (source tree only): ${pattern.source}  ${reason}`);
  console.log(`\nPath-leak exemption: ${EMSCRIPTEN_HOME} (Emscripten's constant virtual file system home; appears in the generated runtime glue).`);
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes('--list-allowlist')) { printAllowlist(); return 0; }
  const json = args.includes('--json');
  const packages = [];
  let treeRoot = null;
  for (let index = 0; index < args.length; index++) {
    if (args[index] === '--package') { packages.push(args[++index]); continue; }
    if (args[index].startsWith('--')) continue;
    treeRoot = args[index];
  }
  if (args.includes('--package') && !packages.length) { console.error('--package needs a directory'); return 2; }
  const jobs = [];
  if (!packages.length || treeRoot) jobs.push({ label: 'tree', root: treeRoot || dirname(SELF), package: false });
  for (const directory of packages) jobs.push({ label: 'package', root: directory, package: true });
  let total = 0;
  const report = [];
  for (const job of jobs) {
    allowHits.clear();
    const result = await scanTree(job.root, { package: job.package });
    total += result.length;
    report.push({ label: job.label, root: job.root, findings: result, allowlistHits: Object.fromEntries(allowHits) });
    if (!json) {
      console.log(`[${MODE}] ${job.label} scan of ${job.root}: ${result.length} finding(s)`);
      for (const finding of result) console.log(`  ${finding.rule}  ${finding.path}${finding.line ? ':' + finding.line : ''}  ${finding.detail}`);
      if (allowHits.size) {
        console.log('  allowlist entries used:');
        for (const [key, count] of allowHits) console.log(`    ${count}x  ${key.replace('\u0001', '  --  ')}`);
      }
    }
  }
  if (json) console.log(JSON.stringify(report, null, 2));
  return total ? 1 : 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) process.exitCode = await main();
